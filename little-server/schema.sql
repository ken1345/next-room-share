CREATE TABLE IF NOT EXISTS listings (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    host_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    title TEXT NOT NULL,
    description LONGTEXT,
    price INT NOT NULL,
    address TEXT,
    latitude DOUBLE,
    longitude DOUBLE,
    prefecture VARCHAR(100),
    city VARCHAR(150),
    station_line TEXT,
    station_name TEXT,
    minutes_to_station INT,
    room_type VARCHAR(80),
    gender_restriction VARCHAR(80),
    is_public BOOLEAN DEFAULT TRUE,
    view_count INT,
    favorites_count INT,
    inquiry_count INT,
    slug TEXT,
    slug_jp TEXT,
    building_type TEXT,
    amenities JSON,
    images JSON,
    equipment JSON,
    personal_equipment JSON,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6),
    INDEX listings_public_updated (is_public, updated_at, id),
    INDEX listings_owner_updated (host_id, updated_at, id),
    INDEX listings_location (prefecture, city, is_public)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
